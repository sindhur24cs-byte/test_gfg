import java.util.ArrayList;
import java.util.Collections;

class Solution {
    // Method to return the maximum element in the ArrayList
    public int maximumElement(ArrayList<Integer> arr) {
        return Collections.max(arr);
    }

    // Method to return the minimum element in the ArrayList
    public int minimumElement(ArrayList<Integer> arr) {
        return Collections.min(arr);
    }
}